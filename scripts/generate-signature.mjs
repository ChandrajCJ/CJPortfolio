/**
 * Turns a name set in a script font into SVG path data for the scroll-drawn
 * signature in the contact section, so the page draws real letter outlines
 * without loading the font at runtime.
 *
 * Font: Mrs Saint Delafield (SIL Open Font License 1.1), via @fontsource.
 * Swap NAME for a traced real signature later - the component only needs
 * { viewBox, paths }.
 *
 *   node scripts/generate-signature.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import opentype from 'opentype.js'

const NAME = 'Chandraj'
const SIZE = 120

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const fontFile = resolve(root, 'node_modules/@fontsource/mrs-saint-delafield/files/mrs-saint-delafield-latin-400-normal.woff')
const buffer = readFileSync(fontFile)
const font = opentype.parse(buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength))

// Serialised by hand: opentype.js 2's toPathData() takes an options object and
// emitted NaN coordinates for some glyphs when given a precision number.
const fmt = (n) => (Math.round(n * 10) / 10).toString()
const round = (n) => Math.round(n * 10) / 10
const toD = (commands) =>
  commands
    .map((c) => {
      if (c.type === 'M' || c.type === 'L') return `${c.type}${fmt(c.x)} ${fmt(c.y)}`
      if (c.type === 'Q') return `Q${fmt(c.x1)} ${fmt(c.y1)} ${fmt(c.x)} ${fmt(c.y)}`
      if (c.type === 'C') return `C${fmt(c.x1)} ${fmt(c.y1)} ${fmt(c.x2)} ${fmt(c.y2)} ${fmt(c.x)} ${fmt(c.y)}`
      return 'Z'
    })
    .join('')

// One path per glyph, so each letter can be drawn in turn rather than all at once.
const glyphs = font.getPaths(NAME, 0, SIZE, SIZE)
const paths = glyphs.map((p) => toD(p.commands)).filter(Boolean)
if (paths.some((d) => d.includes('NaN'))) throw new Error('glyph path contains NaN')

const box = glyphs.reduce(
  (acc, p) => {
    const b = p.getBoundingBox()
    if (!Number.isFinite(b.x1)) return acc
    return { x1: Math.min(acc.x1, b.x1), y1: Math.min(acc.y1, b.y1), x2: Math.max(acc.x2, b.x2), y2: Math.max(acc.y2, b.y2) }
  },
  { x1: Infinity, y1: Infinity, x2: -Infinity, y2: -Infinity },
)
/**
 * The tittle of the final j: the contour of the last glyph that sits wholly
 * above its main stroke. The Astro orb lands on it as it travels the page.
 */
function findDot(glyph) {
  const contours = []
  for (const c of glyph.commands) {
    if (c.type === 'M') contours.push([])
    const pts = contours.at(-1)
    for (const [kx, ky] of [['x', 'y'], ['x1', 'y1'], ['x2', 'y2']]) {
      if (c[kx] !== undefined) pts.push([c[kx], c[ky]])
    }
  }
  const boxes = contours
    .filter((pts) => pts.length)
    .map((pts) => {
      const xs = pts.map((p) => p[0])
      const ys = pts.map((p) => p[1])
      return { x1: Math.min(...xs), x2: Math.max(...xs), y1: Math.min(...ys), y2: Math.max(...ys) }
    })
  const area = (b) => (b.x2 - b.x1) * (b.y2 - b.y1)
  const main = boxes.reduce((m, b) => (area(b) > area(m) ? b : m))
  const above = boxes.filter((b) => b !== main && b.y2 < main.y1)
  if (!above.length) return null
  const dot = above.reduce((m, b) => (area(b) < area(m) ? b : m))
  return { x: round((dot.x1 + dot.x2) / 2), y: round((dot.y1 + dot.y2) / 2), r: round(Math.max(dot.x2 - dot.x1, dot.y2 - dot.y1) / 2) }
}
const dot = findDot(glyphs.at(-1))
if (!dot) throw new Error(`no dot found above the last glyph of ${NAME}`)

const pad = 6
const viewBox = [box.x1 - pad, box.y1 - pad, box.x2 - box.x1 + pad * 2, box.y2 - box.y1 + pad * 2].map((n) => Math.round(n)).join(' ')

const out = `// Generated by scripts/generate-signature.mjs from the Mrs Saint Delafield font
// (SIL OFL 1.1). Do not edit by hand.
export const signature = ${JSON.stringify({ name: NAME, viewBox, dot, paths }, null, 2)}
`
writeFileSync(resolve(root, 'src/data/signature.js'), out)
console.log(`wrote src/data/signature.js (${paths.length} glyph paths, viewBox ${viewBox}, dot ${JSON.stringify(dot)})`)
